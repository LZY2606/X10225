package jsondiff

import (
	"slices"
	"strings"
	"unsafe"
)

// A Differ generates JSON Patch (RFC 6902).
// The zero value is an empty generator ready to use.
type Differ struct {
	hashmap          map[uint64]jsonNode
	opts             options
	patch            Patch
	snapshotPatchLen int
	targetBytes      []byte
	ptr              pointer
	hasher           hasher
	isCompact        bool
	compactInPlace   bool

	// Diagnostic counters of the latest comparison. They are reset
	// at the beginning of every comparison and never shared with
	// another Differ, which makes concurrent comparisons isolated.
	stats MatchStats

	// activeMatcher is the array matcher currently consuming the
	// produced operations, if any. It is nil outside of LCS array
	// comparisons and allows operation factorization to reuse the
	// memoized equality table when discovering move candidates.
	activeMatcher *arrayMatcher
	// activeAddJ is the target index of the addition being
	// factorized, or -1 when factorization runs without a matcher.
	activeAddJ int

	// Test-only recoverable-failure seam; nil in production.
	matchFailpoint *matchFailpoint
}

type (
	marshalFunc   func(any) ([]byte, error)
	unmarshalFunc func([]byte, any) error
)

type options struct {
	ignores     map[string]struct{}
	marshal     marshalFunc
	unmarshal   unmarshalFunc
	hasIgnore   bool
	factorize   bool
	rationalize bool
	invertible  bool
	equivalent  bool
	lcs         bool
}

type jsonNode struct {
	val any
	ptr string
}

// Reset resets the Differ to be empty, but it retains the
// underlying storage for use by future comparisons.
func (d *Differ) Reset() {
	d.patch = d.patch[:0]
	d.ptr.reset()

	// Optimized map clear.
	for k := range d.hashmap {
		delete(d.hashmap, k)
	}
	d.stats = MatchStats{}
	d.activeMatcher = nil
	d.activeAddJ = -1
}

// Stats returns the diagnostic counters collected during the most
// recent comparison performed by the Differ. The returned value is a
// snapshot: mutating it never affects the Differ, and it stays valid
// after subsequent comparisons or resets.
//
// Counters are diagnostic only. They do not influence the generated
// patch, are reset on every comparison, and are local to the Differ,
// so concurrent comparisons on distinct Differ instances are fully
// isolated.
func (d *Differ) Stats() MatchStats {
	return d.stats.clone()
}

// WithOpts applies the given options to the Differ
// instance and returns it to allow chained calls.
func (d *Differ) WithOpts(opts ...Option) *Differ {
	for _, o := range opts {
		o(d)
	}
	return d
}

// Patch returns the list of JSON patch operations
// generated by the Differ instance. The patch is
// valid for usage until the next comparison or reset.
func (d *Differ) Patch() Patch {
	return d.patch
}

// Compare computes the differences between src and tgt
// as a series of JSON Patch operations.
func (d *Differ) Compare(src, tgt interface{}) {
	d.stats = MatchStats{}
	d.activeMatcher = nil
	d.activeAddJ = -1

	// Patch length before the comparison, used to roll back every
	// emitted operation when a stage aborts with a recoverable error.
	start := len(d.patch)
	defer func() {
		if r := recover(); r != nil {
			if r == ErrUnsupported {
				d.rollback(start)
			}
			panic(r)
		}
	}()

	if d.opts.factorize {
		d.prepare(d.ptr, src, tgt)
		d.ptr.reset()
	}
	if d.opts.rationalize {
		if !d.isCompact {
			if d.compactInPlace {
				d.targetBytes = compactInPlace(d.targetBytes)
			} else {
				d.targetBytes = compact(d.targetBytes)
			}
		}
	}
	d.diff(d.ptr, src, tgt, b2s(d.targetBytes))
}

// abort stops the current comparison with the given sentinel. It is
// invoked from internal stages that cannot continue.
func (d *Differ) abort(err error) {
	panic(err)
}

// rollback restores the Differ to the state it had before the
// comparison that failed, so that no partial patch, diagnostic
// counter or temporary matcher state leaks to the caller or to a
// later retry.
func (d *Differ) rollback(start int) {
	d.patch = d.patch[:start]
	d.ptr.reset()
	for k := range d.hashmap {
		delete(d.hashmap, k)
	}
	d.stats = MatchStats{}
	d.activeMatcher = nil
	d.activeAddJ = -1
}

func (d *Differ) isIgnored(ptr pointer) bool {
	// Fast path, inlined map check.
	if !d.opts.hasIgnore {
		return false
	}
	// Slow path.
	// Outlined so that the fast path can be inlined.
	return d.findIgnored(ptr)
}

func (d *Differ) findIgnored(ptr pointer) bool {
	_, found := d.opts.ignores[ptr.string()]
	return found
}

func (d *Differ) diff(ptr pointer, src, tgt interface{}, doc string) {
	if d.isIgnored(ptr) {
		return
	}
	if !areComparable(src, tgt) {
		if ptr.isRoot() {
			// If incomparable values are located at the root
			// of the document, use an add operation to replace
			// the entire content of the document.
			// https://tools.ietf.org/html/rfc6902#section-4.1
			d.patch = d.patch.append(OperationAdd, emptyPointer, ptr.copy(), src, tgt, 0)
		} else {
			// Values are incomparable, generate a replacement.
			d.replace(ptr.copy(), src, tgt, doc)
		}
		return
	}
	if deepEqual(src, tgt) {
		return
	}
	// Save the current size of the patch to detect later
	// on if we have new operations to rationalize.
	size := len(d.patch)

	// Values are comparable, but are not
	// equivalent.
	switch val := src.(type) {
	case []interface{}:
		if d.opts.lcs {
			d.compareArraysLCS(ptr, val, tgt.([]interface{}), doc)
		} else {
			d.compareArrays(ptr, val, tgt.([]interface{}), doc)
		}
	case map[string]interface{}:
		d.compareObjects(ptr, val, tgt.(map[string]interface{}), doc)
	default:
		// Generate a replace operation for
		// scalar types.
		if !deepEqual(src, tgt) {
			d.replace(ptr.copy(), src, tgt, doc)
			return
		}
	}
	// Rationalize new operations, if any.
	if d.opts.rationalize && len(d.patch) > size {
		d.rationalize(ptr, src, tgt, size, doc)
	}
}

func (d *Differ) prepare(ptr pointer, src, tgt interface{}) {
	// When both values are deeply equals, save
	// the location indexed by the value hash.
	if !areComparable(src, tgt) {
		return
	} else if deepEqual(src, tgt) {
		k := d.digest(tgt, false)
		if d.hashmap == nil {
			d.hashmap = make(map[uint64]jsonNode)
		}
		d.hashmap[k] = jsonNode{
			ptr: ptr.copy(),
			val: tgt,
		}
		return
	}
	// At this point, the source and target values
	// are non-nil and have comparable types.
	switch vsrc := src.(type) {
	case []interface{}:
		oarr := vsrc
		narr := tgt.([]interface{})

		for i := 0; i < min(len(oarr), len(narr)); i++ {
			p := ptr.clone()
			p.appendIndex(i)
			d.prepare(p, oarr[i], narr[i])
		}
	case map[string]interface{}:
		oobj := vsrc
		nobj := tgt.(map[string]interface{})

		for k, v1 := range oobj {
			if v2, ok := nobj[k]; ok {
				p := ptr.clone()
				p.appendKey(k)
				d.prepare(p, v1, v2)
			}
		}
	default:
		// Skipped.
	}
}

func (d *Differ) rationalize(ptr pointer, src, tgt interface{}, lastOpIdx int, doc string) {
	// replaceOp represents a single operation that
	// replace the source document with the target.
	replaceOp := Operation{
		Type:     OperationReplace,
		Path:     ptr.string(), // shallow copy
		OldValue: src,
		Value:    tgt,
		valueLen: len(doc),
	}
	curOps := d.patch[lastOpIdx:]
	curLen := curOps.jsonLength()

	// If one operation is cheaper than many small
	// operations that represents the changes between
	// the two objects, replace the last operations.
	if curLen > replaceOp.jsonLength() {
		d.patch = d.patch[:lastOpIdx]

		// Allocate a new string for the operation's path.
		replaceOp.Path = ptr.copy()

		if d.opts.invertible {
			d.patch = d.patch.append(OperationTest, emptyPointer, replaceOp.Path, nil, src, len(doc))
		}
		d.patch = append(d.patch, replaceOp)
	}
}

// compareObjects generates the patch operations that
// represents the differences between two JSON objects.
func (d *Differ) compareObjects(ptr pointer, src, tgt map[string]interface{}, doc string) {
	cmpSet := make(map[string]uint8, max(len(src), len(tgt)))

	for k := range src {
		cmpSet[k] |= 1 << 0
	}
	for k := range tgt {
		cmpSet[k] |= 1 << 1
	}
	keys := make([]string, 0, len(cmpSet))
	for k := range cmpSet {
		keys = append(keys, k)
	}
	sortStrings(keys)

	ptr.snapshot()
	for _, k := range keys {
		v := cmpSet[k]
		inOld := v&(1<<0) != 0
		inNew := v&(1<<1) != 0

		ptr.appendKey(k)

		switch {
		case inOld && inNew:
			if d.opts.rationalize {
				d.diff(ptr, src[k], tgt[k], findKey(doc, ptr.base.key))
			} else {
				d.diff(ptr, src[k], tgt[k], doc)
			}
		case inOld:
			if !d.isIgnored(ptr) {
				d.remove(ptr.copy(), src[k])
			}
		case inNew:
			if !d.isIgnored(ptr) {
				d.add(ptr.copy(), tgt[k], doc, false)
			}
		}
		ptr.rewind()
	}
}

// compareArrays generates the patch operations that
// represents the differences between two JSON arrays.
func (d *Differ) compareArrays(ptr pointer, src, tgt []interface{}, doc string) {
	ptr.snapshot()
	sl, tl := len(src), len(tgt)
	ml := min(sl, tl)

	// When the source array contains more elements
	// than the target, entries are being removed
	// from the destination and the removal index
	// is always equal to the original array length.
	if tl < sl {
		np := ptr.clone()
		np.appendIndex(ml) // "removal" path
		p := np.copy()
		for i := ml; i < sl; i++ {
			ptr.appendIndex(i)

			if !d.isIgnored(ptr) {
				d.remove(p, src[i])
			}
			ptr.rewind()
		}
		goto comparisons // skip equivalence test since arrays are different
	}
	if d.opts.equivalent && d.unorderedDeepEqualSlice(src, tgt) {
		return
	}
comparisons:
	// Compare the elements at each index present in
	// both the source and destination arrays.
	for i := 0; i < ml; i++ {
		ptr.appendIndex(i)
		if d.opts.rationalize {
			d.diff(ptr, src[i], tgt[i], findIndex(doc, ptr.base.idx))
		} else {
			d.diff(ptr, src[i], tgt[i], doc)
		}
		ptr.rewind()
	}
	// When the target array contains more elements
	// than the source, entries are appended to the
	// destination.
	if tl > sl {
		np := ptr.clone()
		np.appendKey("-") // "append" path
		p := np.copy()
		for i := ml; i < tl; i++ {
			ptr.appendIndex(i)
			if !d.isIgnored(ptr) {
				d.add(p, tgt[i], doc, false)
			}
			ptr.rewind()
		}
	}
}

func (d *Differ) compareArraysLCS(ptr pointer, src, tgt []interface{}, doc string) {
	if len(src) == len(tgt) {
		if d.opts.equivalent && d.unorderedDeepEqualSlice(src, tgt) {
			return
		}
	}
	ptr.snapshot()

	// A single matcher owns element equality, the LCS table and
	// move/copy candidate discovery for this array pair, so each
	// candidate pair is evaluated at most once.
	m := newArrayMatcher(src, tgt)
	m.failAfter(d)
	pairs := m.lcs()
	m.failAfter(d)

	// Publish the matcher for the operations emitted below so that
	// factorization reuses its memoized equality table.
	prevMatcher := d.activeMatcher
	d.activeMatcher = m
	defer func() {
		d.activeMatcher = prevMatcher
		d.activeAddJ = -1
		// Publish the array counters in the deterministic order in
		// which arrays are visited by the diff traversal.
		d.stats.Arrays = append(d.stats.Arrays, m.stats)
		d.stats.Comparisons += m.stats.Comparisons
		d.stats.HashDigests += m.stats.HashDigests
	}()

	d.snapshotPatchLen = len(d.patch)

	var ai, bi int // src && tgt arrows
	var adds, removes int

	adjust := func(i int) int {
		// Adjust index considering add and remove
		// operations that precede it.
		return i + adds - removes
	}

	// Iterate over all the indexs of the LCS, which
	// represent the position of items that are present
	// in both the source and target slices.
	for p := 0; p < len(pairs); p++ {
		ma, mb := pairs[p][0], pairs[p][1]

		// Proceed with addition/deletion or change events
		// until both arrows reach the current index.
		for ai < ma || bi < mb {
			switch {
			case ai < ma && bi < mb:
				// Both arrows points to an item before the
				// current match index, which indicate an
				// equal amount of different items.
				ptr.appendIndex(adjust(ai))
				if d.opts.rationalize {
					d.diff(ptr, src[ai], tgt[bi], findIndex(doc, ptr.base.idx))
				} else {
					d.diff(ptr, src[ai], tgt[bi], doc)
				}
				ptr.rewind()
				ai++
				bi++
			case ai < ma:
				// The left arrow representing the source slice
				// is lower than the current match index, which
				// indicate that a preceding item has been removed.
				ptr.appendIndex(adjust(ai))

				if !d.isIgnored(ptr) {
					d.removeMatched(ptr.copy(), src[ai], m, ai)
				}
				ptr.rewind()
				ai++
				removes++
			default: // bi < mb
				// Opposite case of the previous condition.
				ptr.appendIndex(bi)
				if !d.isIgnored(ptr) {
					d.addMatched(ptr.copy(), tgt[bi], doc, m, bi)
				}
				ptr.rewind()
				bi++
				adds++
			}
		}
		// Both arrows reached the current match index
		// where the elements of the source and target
		// slice are equal, i.e. `src[ai] == tgt[bi]`.
		ai++
		bi++
	}
	// After all index pairs of the LCS have been traversed,
	// the remaining items up to the length of the source and
	// target slices are iterated. The same logic applies to
	// detect addition/deletion or change events.
	for ai < len(src) || bi < len(tgt) {
		switch {
		case ai < len(src) && bi < len(tgt):
			ptr.appendIndex(adjust(ai))
			if d.opts.rationalize {
				d.diff(ptr, src[ai], tgt[bi], findIndex(doc, ptr.base.idx))
			} else {
				d.diff(ptr, src[ai], tgt[bi], doc)
			}
			ptr.rewind()
			ai++
			bi++
		case ai < len(src):
			ptr.appendIndex(adjust(ai))

			if !d.isIgnored(ptr) {
				d.removeMatched(ptr.copy(), src[ai], m, ai)
			}
			ptr.rewind()
			ai++
			removes++
		default: // bi < len(tgt)
			ptr.appendIndex(bi)
			if !d.isIgnored(ptr) {
				d.addMatched(ptr.copy(), tgt[bi], doc, m, bi)
			}
			ptr.rewind()
			bi++
			adds++
		}
	}
}

func (d *Differ) unorderedDeepEqualSlice(src, tgt []interface{}) bool {
	if len(src) != len(tgt) {
		return false
	}

	// Hash source elements into buckets. Digests are only a filter:
	// duplicate values must be paired by multiplicity, and elements
	// that merely share a digest (a hash collision) must be compared
	// for deep equality before being accepted as a match. This keeps
	// the semantics exactly equal to "same multiset of values".
	buckets := make(map[uint64][]int, len(src))
	for i, v := range src {
		k := d.digest(v, d.opts.equivalent)
		buckets[k] = append(buckets[k], i)
	}

	for _, tv := range tgt {
		k := d.digest(tv, d.opts.equivalent)
		bucket := buckets[k]
		matched := -1
		for _, si := range bucket {
			d.stats.Comparisons++
			if deepEqual(src[si], tv) {
				matched = si
				break
			}
		}
		if matched == -1 {
			return false
		}
		// Remove the consumed source index from the bucket.
		bucket = buckets[k]
		for i, si := range bucket {
			if si == matched {
				buckets[k] = append(bucket[:i], bucket[i+1:]...)
				break
			}
		}
	}
	return true
}

// digest computes the hash of v and records it in the diagnostic
// counters. It is the single entry point used by hashing stages.
func (d *Differ) digest(v interface{}, sort bool) uint64 {
	d.stats.HashDigests++
	if d.activeMatcher != nil {
		d.activeMatcher.stats.HashDigests++
	}
	return d.hasher.digest(v, sort)
}

func (d *Differ) replace(path string, src, tgt interface{}, doc string) {
	vl := len(doc)

	if d.opts.invertible {
		d.patch = d.patch.append(OperationTest, emptyPointer, path, nil, src, vl)
	}
	d.patch = d.patch.append(OperationReplace, emptyPointer, path, src, tgt, vl)
}

// add is the factorization entry point used outside of an LCS array
// comparison (object additions and default, index-wise arrays).
func (d *Differ) add(path string, v interface{}, doc string, lcs bool) {
	d.emitAdd(path, v, doc, lcs)
}

// addMatched emits an addition while matching an LCS array. The
// target index and the active matcher let move/copy discovery reuse
// the single, memoized candidate table of the array.
func (d *Differ) addMatched(path string, v interface{}, doc string, m *arrayMatcher, tgtIdx int) {
	d.activeAddJ = tgtIdx
	d.emitAdd(path, v, doc, true)
	d.activeAddJ = -1
}

func (d *Differ) emitAdd(path string, v interface{}, doc string, lcs bool) {
	if !d.opts.factorize {
		d.patch = d.patch.append(OperationAdd, emptyPointer, path, nil, v, 0)
		return
	}
	idx := d.findRemoved(v)
	if idx != -1 {
		op := d.patch[idx]

		// https://tools.ietf.org/html/rfc6902#section-4.4f
		// The "from" location MUST NOT be a proper prefix
		// of the "path" location; i.e., a location cannot
		// be moved into one of its children.
		if !hasProperPathPrefix(op.Path, path) {
			d.patch = d.patch.remove(idx)
			if !lcs {
				d.patch = d.patch.append(OperationMove, op.Path, path, v, v, 0)
			} else {
				d.patch = d.patch.insert(d.snapshotPatchLen, OperationMove, op.Path, path, v, v, 0)
			}
			if d.activeMatcher != nil {
				d.activeMatcher.stats.Moves++
			}
		}
		return
	}
	uptr := d.findUnchanged(v)

	if len(uptr) != 0 && !d.opts.invertible {
		d.patch = d.patch.append(OperationCopy, uptr, path, nil, v, 0)
		if d.activeMatcher != nil {
			d.activeMatcher.stats.CopyCandidates++
		}
	} else {
		d.patch = d.patch.append(OperationAdd, emptyPointer, path, nil, v, len(doc))
	}
}

// remove emits a removal outside of an LCS array comparison.
func (d *Differ) remove(path string, v interface{}) {
	d.emitRemove(path, v, nil, -1)
}

// removeMatched emits a removal while matching an LCS array and
// tags it with the matcher and source index, so that a later
// addition can discover it as a move candidate through the
// memoized equality table instead of re-evaluating equality.
func (d *Differ) removeMatched(path string, v interface{}, m *arrayMatcher, srcIdx int) {
	d.emitRemove(path, v, m, srcIdx)
}

func (d *Differ) emitRemove(path string, v interface{}, m *arrayMatcher, srcIdx int) {
	if d.opts.invertible {
		d.patch = d.patch.append(OperationTest, emptyPointer, path, nil, v, 0)
	}
	op := Operation{
		Type:     OperationRemove,
		Path:     path,
		OldValue: v,
	}
	if m != nil {
		op.am = m
		op.srcIdx = srcIdx
	}
	d.patch = append(d.patch, op)
}

func (d *Differ) findUnchanged(v interface{}) string {
	if d.hashmap != nil {
		k := d.digest(v, false)
		node, ok := d.hashmap[k]
		// The digest only narrows the lookup. Confirm deep equality
		// so that an unrelated value sharing the digest (a hash
		// collision) can never be paired with the added value.
		if ok && d.equalValues(node.val, v) {
			return node.ptr
		}
	}
	return emptyPointer
}

func (d *Differ) findRemoved(v interface{}) int {
	m := d.activeMatcher
	for i := 0; i < len(d.patch); i++ {
		op := d.patch[i]
		if op.Type != OperationRemove {
			continue
		}
		// A removal tagged with the active matcher belongs to the
		// current LCS array: its equality against the addition was
		// already evaluated once while building the candidate table.
		if m != nil && op.am == m {
			if m.equal(op.srcIdx, d.activeAddJ) {
				return i
			}
			continue
		}
		if d.equalValues(op.OldValue, v) {
			return i
		}
	}
	return -1
}

// equalValues reports the deep equality of two factorization
// candidates. It is the counted equality entry point used outside of
// the memoized array table (cross-array removals and unchanged-value
// lookup), so the total number of candidate comparisons stays
// observable.
func (d *Differ) equalValues(src, tgt interface{}) bool {
	d.stats.Comparisons++
	return deepEqual(src, tgt)
}

func hasProperPathPrefix(prefix, path string) bool {
	if prefix == emptyPointer {
		return path != emptyPointer
	}
	if !strings.HasPrefix(path, prefix) {
		return false
	}
	if len(path) == len(prefix) {
		return false
	}
	return path[len(prefix)] == separator
}

func (d *Differ) applyOpts(opts ...Option) {
	for _, opt := range opts {
		if opt != nil {
			opt(d)
		}
	}
}

func sortStrings(v []string) {
	if len(v) <= 20 {
		insertionSort(v)
	} else {
		slices.Sort(v)
	}
}

func insertionSort(v []string) {
	for i := 0; i < len(v); i++ {
		for j := i; j > 0 && v[j-1] > v[j]; j-- {
			v[j], v[j-1] = v[j-1], v[j]
		}
	}
}

func b2s(b []byte) string {
	return *(*string)(unsafe.Pointer(&b))
}
