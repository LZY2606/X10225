package jsondiff

import (
	"fmt"
	"slices"
	"strings"
	"unsafe"
)

// A Differ generates JSON Patch (RFC 6902).
// The zero value is an empty generator ready to use.
type Differ struct {
	hashmap          map[uint64]jsonNode
	opts             options
	patch            Patch
	snapshotPatchLen int
	targetBytes      []byte
	ptr              pointer
	hasher           hasher
	match            *arrayMatcher
	isCompact        bool
	compactInPlace   bool

	// Diagnostic-only seams. They are unexported and used
	// exclusively by in-package tests to simulate a hash
	// collision and an injectable mid-comparison failure.
	// Production callers can neither set nor observe them.
	digestSpoof map[uint64]uint64
	matchFault  func(phase matchPhase)
}

type (
	marshalFunc   func(any) ([]byte, error)
	unmarshalFunc func([]byte, any) error
)

type options struct {
	ignores     map[string]struct{}
	marshal     marshalFunc
	unmarshal   unmarshalFunc
	hasIgnore   bool
	factorize   bool
	rationalize bool
	invertible  bool
	equivalent  bool
	lcs         bool
}

type jsonNode struct {
	val any
	ptr string
}

// Reset resets the Differ to be empty, but it retains the
// underlying storage for use by future comparisons.
func (d *Differ) Reset() {
	d.patch = d.patch[:0]
	d.ptr.reset()

	// Optimized map clear.
	for k := range d.hashmap {
		delete(d.hashmap, k)
	}
}

// WithOpts applies the given options to the Differ
// instance and returns it to allow chained calls.
func (d *Differ) WithOpts(opts ...Option) *Differ {
	for _, o := range opts {
		o(d)
	}
	return d
}

// Patch returns the list of JSON patch operations
// generated by the Differ instance. The patch is
// valid for usage until the next comparison or reset.
func (d *Differ) Patch() Patch {
	return d.patch
}

// Compare computes the differences between src and tgt
// as a series of JSON Patch operations.
//
// Each invocation starts from a clean, call-scoped state:
// the pointer builder and the diagnostic array matcher are
// rebuilt, while factorization data is prepared fresh. If
// the comparison fails midway (for instance when an input
// holds a value of an unsupported JSON type), the patch and
// the factorization index are restored to their state on
// entry, so a subsequent retry with identical inputs is
// not affected by half-written state.
func (d *Differ) Compare(src, tgt interface{}) {
	savedPatch := d.patch[:len(d.patch):len(d.patch)]
	savedHashmap := d.hashmap
	savedSnapshot := d.snapshotPatchLen

	d.ptr.reset()
	d.match = newArrayMatcher(d)
	if d.opts.factorize {
		d.hashmap = make(map[uint64]jsonNode)
		d.prepare(d.ptr, src, tgt)
		d.ptr.reset()
	}
	if d.opts.rationalize {
		if !d.isCompact {
			if d.compactInPlace {
				d.targetBytes = compactInPlace(d.targetBytes)
			} else {
				d.targetBytes = compact(d.targetBytes)
			}
		}
	}

	defer func() {
		if r := recover(); r != nil {
			// Roll back every shared accumulator the
			// comparison may have mutated, then re-panic so
			// that the public error model is preserved.
			d.patch = savedPatch
			d.hashmap = savedHashmap
			d.snapshotPatchLen = savedSnapshot
			d.ptr.reset()
			panic(r)
		}
	}()
	d.diff(d.ptr, src, tgt, b2s(d.targetBytes))
}

// digest is the single hashing entry point shared by
// preparation, unordered equivalence and move/copy
// candidate discovery. A digest only pre-filters
// candidates: every digest-based match is still confirmed
// through deepEqual before it can influence a patch.
func (d *Differ) digest(v interface{}, sort bool) uint64 {
	h := d.hasher.digest(v, sort)
	if d.digestSpoof != nil {
		if spoofed, ok := d.digestSpoof[h]; ok {
			return spoofed
		}
	}
	return h
}

// matchCounters returns the diagnostic counters of the
// last comparison. It is intentionally unexported: the
// counters are observability-only and never affect results.
func (d *Differ) matchCounters() MatchCounters {
	if d.match == nil {
		return MatchCounters{}
	}
	return d.match.counters
}

func (d *Differ) isIgnored(ptr pointer) bool {
	// Fast path, inlined map check.
	if !d.opts.hasIgnore {
		return false
	}
	// Slow path.
	// Outlined so that the fast path can be inlined.
	return d.findIgnored(ptr)
}

func (d *Differ) findIgnored(ptr pointer) bool {
	_, found := d.opts.ignores[ptr.string()]
	return found
}

func (d *Differ) diff(ptr pointer, src, tgt interface{}, doc string) {
	if d.isIgnored(ptr) {
		return
	}
	if !areComparable(src, tgt) {
		if ptr.isRoot() {
			// If incomparable values are located at the root
			// of the document, use an add operation to replace
			// the entire content of the document.
			// https://tools.ietf.org/html/rfc6902#section-4.1
			d.patch = d.patch.append(OperationAdd, emptyPointer, ptr.copy(), src, tgt, 0)
		} else {
			// Values are incomparable, generate a replacement.
			d.replace(ptr.copy(), src, tgt, doc)
		}
		return
	}
	if deepEqual(src, tgt) {
		return
	}
	// Save the current size of the patch to detect later
	// on if we have new operations to rationalize.
	size := len(d.patch)

	// Values are comparable, but are not
	// equivalent.
	switch val := src.(type) {
	case []interface{}:
		if d.opts.lcs {
			d.compareArraysLCS(ptr, val, tgt.([]interface{}), doc)
		} else {
			d.compareArrays(ptr, val, tgt.([]interface{}), doc)
		}
	case map[string]interface{}:
		d.compareObjects(ptr, val, tgt.(map[string]interface{}), doc)
	default:
		// Generate a replace operation for
		// scalar types.
		if !deepEqual(src, tgt) {
			d.replace(ptr.copy(), src, tgt, doc)
			return
		}
	}
	// Rationalize new operations, if any.
	if d.opts.rationalize && len(d.patch) > size {
		d.rationalize(ptr, src, tgt, size, doc)
	}
}

func (d *Differ) prepare(ptr pointer, src, tgt interface{}) {
	// When both values are deeply equals, save
	// the location indexed by the value hash.
	if !areComparable(src, tgt) {
		return
	} else if deepEqual(src, tgt) {
		k := d.digest(tgt, false)
		if d.hashmap == nil {
			d.hashmap = make(map[uint64]jsonNode)
		}
		d.hashmap[k] = jsonNode{
			ptr: ptr.copy(),
			val: tgt,
		}
		return
	}
	// At this point, the source and target values
	// are non-nil and have comparable types.
	switch vsrc := src.(type) {
	case []interface{}:
		oarr := vsrc
		narr := tgt.([]interface{})

		for i := 0; i < min(len(oarr), len(narr)); i++ {
			p := ptr.clone()
			p.appendIndex(i)
			d.prepare(p, oarr[i], narr[i])
		}
	case map[string]interface{}:
		oobj := vsrc
		nobj := tgt.(map[string]interface{})

		for k, v1 := range oobj {
			if v2, ok := nobj[k]; ok {
				p := ptr.clone()
				p.appendKey(k)
				d.prepare(p, v1, v2)
			}
		}
	default:
		// Skipped.
	}
}

func (d *Differ) rationalize(ptr pointer, src, tgt interface{}, lastOpIdx int, doc string) {
	// replaceOp represents a single operation that
	// replace the source document with the target.
	replaceOp := Operation{
		Type:     OperationReplace,
		Path:     ptr.string(), // shallow copy
		OldValue: src,
		Value:    tgt,
		valueLen: len(doc),
	}
	curOps := d.patch[lastOpIdx:]
	curLen := curOps.jsonLength()

	// If one operation is cheaper than many small
	// operations that represents the changes between
	// the two objects, replace the last operations.
	if curLen > replaceOp.jsonLength() {
		d.patch = d.patch[:lastOpIdx]

		// Allocate a new string for the operation's path.
		replaceOp.Path = ptr.copy()

		if d.opts.invertible {
			d.patch = d.patch.append(OperationTest, emptyPointer, replaceOp.Path, nil, src, len(doc))
		}
		d.patch = append(d.patch, replaceOp)
	}
}

// compareObjects generates the patch operations that
// represents the differences between two JSON objects.
func (d *Differ) compareObjects(ptr pointer, src, tgt map[string]interface{}, doc string) {
	cmpSet := make(map[string]uint8, max(len(src), len(tgt)))

	for k := range src {
		cmpSet[k] |= 1 << 0
	}
	for k := range tgt {
		cmpSet[k] |= 1 << 1
	}
	keys := make([]string, 0, len(cmpSet))
	for k := range cmpSet {
		keys = append(keys, k)
	}
	sortStrings(keys)

	ptr.snapshot()
	for _, k := range keys {
		v := cmpSet[k]
		inOld := v&(1<<0) != 0
		inNew := v&(1<<1) != 0

		ptr.appendKey(k)

		switch {
		case inOld && inNew:
			if d.opts.rationalize {
				d.diff(ptr, src[k], tgt[k], findKey(doc, ptr.base.key))
			} else {
				d.diff(ptr, src[k], tgt[k], doc)
			}
		case inOld:
			if !d.isIgnored(ptr) {
				d.remove(ptr.copy(), src[k])
			}
		case inNew:
			if !d.isIgnored(ptr) {
				d.add(ptr.copy(), tgt[k], doc, false)
			}
		}
		ptr.rewind()
	}
}

// compareArrays generates the patch operations that
// represents the differences between two JSON arrays.
func (d *Differ) compareArrays(ptr pointer, src, tgt []interface{}, doc string) {
	ptr.snapshot()
	sl, tl := len(src), len(tgt)
	ml := min(sl, tl)

	// When the source array contains more elements
	// than the target, entries are being removed
	// from the destination and the removal index
	// is always equal to the original array length.
	if tl < sl {
		np := ptr.clone()
		np.appendIndex(ml) // "removal" path
		p := np.copy()
		for i := ml; i < sl; i++ {
			ptr.appendIndex(i)

			if !d.isIgnored(ptr) {
				d.remove(p, src[i])
			}
			ptr.rewind()
		}
		goto comparisons // skip equivalence test since arrays are different
	}
	if d.opts.equivalent && d.unorderedDeepEqualSlice(src, tgt) {
		return
	}
comparisons:
	// Compare the elements at each index present in
	// both the source and destination arrays.
	for i := 0; i < ml; i++ {
		ptr.appendIndex(i)
		if d.opts.rationalize {
			d.diff(ptr, src[i], tgt[i], findIndex(doc, ptr.base.idx))
		} else {
			d.diff(ptr, src[i], tgt[i], doc)
		}
		ptr.rewind()
	}
	// When the target array contains more elements
	// than the source, entries are appended to the
	// destination.
	if tl > sl {
		np := ptr.clone()
		np.appendKey("-") // "append" path
		p := np.copy()
		for i := ml; i < tl; i++ {
			ptr.appendIndex(i)
			if !d.isIgnored(ptr) {
				d.add(p, tgt[i], doc, false)
			}
			ptr.rewind()
		}
	}
}

func (d *Differ) compareArraysLCS(ptr pointer, src, tgt []interface{}, doc string) {
	if len(src) == len(tgt) {
		if d.opts.equivalent && d.unorderedDeepEqualSlice(src, tgt) {
			return
		}
	}
	ptr.snapshot()
	pairs := d.match.lcs(src, tgt)
	regionPrefix := ptr.copy()

	// Generate the move/copy factored region under an
	// isolated candidate scope, so a rejected attempt can be
	// retried conservatively without touching candidates
	// emitted by enclosing arrays or by sibling values.
	d.match.beginRegion(regionPrefix)
	regionStart := len(d.patch)
	d.snapshotPatchLen = regionStart

	d.generateLCSWalk(ptr, src, tgt, doc, pairs)

	region := d.patch[regionStart:]
	if arrayRegionValid(regionPrefix, src, tgt, region) {
		d.match.commitRegion()
		return
	}
	// The factored region cannot be proven applicable:
	// duplicated values or interleaved moves may pair
	// ambiguously. Roll it back and regenerate the array
	// with the conservative positional algorithm, which is
	// always applicable, rather than guessing a move.
	d.patch = d.patch[:regionStart]
	d.match.rollbackRegion()

	d.match.beginRegion(regionPrefix)
	d.match.currentRegion().conservative = true
	d.generatePositionalArray(ptr, src, tgt, doc)
	conservative := d.patch[regionStart:]
	if !arrayRegionValid(regionPrefix, src, tgt, conservative) {
		panic(fmt.Errorf("jsondiff: conservative array diff failed to apply at %q", regionPrefix))
	}
	d.match.commitRegion()
}

// generateLCSWalk emits the LCS-driven add/remove/replace
// operations for one array and lets factorization convert
// removal/addition pairs into moves through the matcher.
func (d *Differ) generateLCSWalk(ptr pointer, src, tgt []interface{}, doc string, pairs [][2]int) {
	var ai, bi int
	var adds, removes int

	adjust := func(i int) int {
		return i + adds - removes
	}
	emitDiff := func() {
		ptr.appendIndex(adjust(ai))
		if d.opts.rationalize {
			d.diff(ptr, src[ai], tgt[bi], findIndex(doc, ptr.base.idx))
		} else {
			d.diff(ptr, src[ai], tgt[bi], doc)
		}
		ptr.rewind()
	}

	for p := 0; p < len(pairs); p++ {
		ma, mb := pairs[p][0], pairs[p][1]
		for ai < ma || bi < mb {
			switch {
			case ai < ma && bi < mb:
				emitDiff()
				ai++
				bi++
			case ai < ma:
				ptr.appendIndex(adjust(ai))
				if !d.isIgnored(ptr) {
					d.remove(ptr.copy(), src[ai])
				}
				ptr.rewind()
				ai++
				removes++
			default:
				ptr.appendIndex(bi)
				if !d.isIgnored(ptr) {
					d.add(ptr.copy(), tgt[bi], doc, true)
				}
				ptr.rewind()
				bi++
				adds++
			}
		}
		ai++
		bi++
	}
	for ai < len(src) || bi < len(tgt) {
		switch {
		case ai < len(src) && bi < len(tgt):
			emitDiff()
			ai++
			bi++
		case ai < len(src):
			ptr.appendIndex(adjust(ai))
			if !d.isIgnored(ptr) {
				d.remove(ptr.copy(), src[ai])
			}
			ptr.rewind()
			ai++
			removes++
		default:
			ptr.appendIndex(bi)
			if !d.isIgnored(ptr) {
				d.add(ptr.copy(), tgt[bi], doc, true)
			}
			ptr.rewind()
			bi++
			adds++
		}
	}
}

// generatePositionalArray emits the non-LCS, slot-by-slot
// comparison for one array: common indices are diffed,
// surplus source elements are removed and extra target
// elements are appended. Factorization remains available
// across array boundaries (whole-object moves and copies of
// unchanged values), while same-array moves are suppressed
// by the conservative region scope.
func (d *Differ) generatePositionalArray(ptr pointer, src, tgt []interface{}, doc string) {
	sl, tl := len(src), len(tgt)
	ml := min(sl, tl)

	ptr.snapshot()
	for i := 0; i < ml; i++ {
		ptr.appendIndex(i)
		if d.opts.rationalize {
			d.diff(ptr, src[i], tgt[i], findIndex(doc, ptr.base.idx))
		} else {
			d.diff(ptr, src[i], tgt[i], doc)
		}
		ptr.rewind()
	}
	for i := ml; i < sl; i++ {
		ptr.appendIndex(i)
		if !d.isIgnored(ptr) {
			d.remove(ptr.copy(), src[i])
		}
		ptr.rewind()
	}
	if tl > sl {
		np := ptr.clone()
		np.appendKey("-")
		ap := np.copy()
		for i := ml; i < tl; i++ {
			ptr.appendIndex(i)
			if !d.isIgnored(ptr) {
				d.add(ap, tgt[i], doc, false)
			}
			ptr.rewind()
		}
	}
}

func (d *Differ) unorderedDeepEqualSlice(src, tgt []interface{}) bool {
	if d.match == nil {
		// Standalone use outside of a top-level comparison.
		d.match = newArrayMatcher(d)
	}
	return d.match.unorderedEqual(src, tgt)
}

func (d *Differ) replace(path string, src, tgt interface{}, doc string) {
	vl := len(doc)

	if d.opts.invertible {
		d.patch = d.patch.append(OperationTest, emptyPointer, path, nil, src, vl)
	}
	d.patch = d.patch.append(OperationReplace, emptyPointer, path, src, tgt, vl)
}

func (d *Differ) add(path string, v interface{}, doc string, lcs bool) {
	if !d.opts.factorize {
		d.patch = d.patch.append(OperationAdd, emptyPointer, path, nil, v, 0)
		return
	}
	idx := d.match.findRemoved(d, path, v)
	switch idx {
	case -1:
		// No reusable removed value; fall back to a copy of
		// an unchanged value, or a plain addition.
	case -2:
		// The only matching candidate cannot be moved into
		// its own child path.
		return
	default:
		op := d.patch[idx]
		d.patch = d.patch.remove(idx)
		if !lcs {
			d.patch = d.patch.append(OperationMove, op.Path, path, v, v, 0)
		} else {
			d.patch = d.patch.insert(d.snapshotPatchLen, OperationMove, op.Path, path, v, v, 0)
		}
		return
	}
	uptr := d.findUnchanged(v)

	if len(uptr) != 0 && !d.opts.invertible &&
		d.match.copySourceAllowed(uptr, path) {
		d.patch = d.patch.append(OperationCopy, uptr, path, nil, v, 0)
	} else {
		d.patch = d.patch.append(OperationAdd, emptyPointer, path, nil, v, len(doc))
	}
}

func (d *Differ) remove(path string, v interface{}) {
	if d.opts.invertible {
		d.patch = d.patch.append(OperationTest, emptyPointer, path, nil, v, 0)
	}
	d.patch = d.patch.append(OperationRemove, emptyPointer, path, v, nil, 0)
	if d.opts.factorize {
		// Register the move candidate exactly once, when
		// the removal is emitted, so later additions probe a
		// precomputed, digest-indexed candidate set.
		d.match.registerRemoved(path, v)
	}
}

func (d *Differ) findUnchanged(v interface{}) string {
	if d.hashmap != nil {
		k := d.digest(v, false)
		node, ok := d.hashmap[k]
		if ok && deepEqual(node.val, v) {
			// Confirm the digest hit structurally; two
			// distinct values sharing a digest must not be
			// treated as copy sources of each other.
			return node.ptr
		}
	}
	return emptyPointer
}

func hasProperPathPrefix(prefix, path string) bool {
	if prefix == emptyPointer {
		return path != emptyPointer
	}
	if !strings.HasPrefix(path, prefix) {
		return false
	}
	if len(path) == len(prefix) {
		return false
	}
	return path[len(prefix)] == separator
}

func (d *Differ) applyOpts(opts ...Option) {
	for _, opt := range opts {
		if opt != nil {
			opt(d)
		}
	}
}

func sortStrings(v []string) {
	if len(v) <= 20 {
		insertionSort(v)
	} else {
		slices.Sort(v)
	}
}

func insertionSort(v []string) {
	for i := 0; i < len(v); i++ {
		for j := i; j > 0 && v[j-1] > v[j]; j-- {
			v[j], v[j-1] = v[j-1], v[j]
		}
	}
}

func b2s(b []byte) string {
	return *(*string)(unsafe.Pointer(&b))
}
